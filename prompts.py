def format_product_data(product: dict) -> dict:
    """Форматирует данные товара для промпта"""
    specs_text = ""
    if product.get("specs"):
        for key, value in product["specs"].items():
            specs_text += f"- {key}: {value}\n"
    else:
        specs_text = "Не предоставлены"
    
    applications = product.get("applications", [])
    apps_text = "\n".join(f"- {app}" for app in applications) if applications else "Не указаны"
    
    return {
        "name": product.get("name", "Не указано"),
        "manufacturer": product.get("manufacturer", "Не указан"),
        "category": product.get("category", "Не указана"),
        "price": product.get("price", "Не указана"),
        "currency": product.get("currency", "RUR"),
        "specs_text": specs_text,
        "description": product.get("description", "Не предоставлено"),
        "applications": apps_text
    }